// Regenerates src/builtin-fixtures.ts from fixtures/*.json. Run it after
// editing, adding or removing a case:
//
//     pnpm --filter @formancy/conformance fixtures:embed
//
// The JSON directory is the source of truth: fixtures are data, and a third
// party writing a Vue or Svelte renderer — or a driver in another language —
// reads the files, not a TypeScript module. The embedded copy exists because
// the suite also has to run where there is no filesystem: a renderer's tests
// run in a browser, and `loadFixtures` cannot help there.
//
// Deliberately plain .mjs outside src/, so the package's typecheck stays free
// of Node types. Library code must never import node:fs.
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const fixturesDirectory = new URL('../fixtures/', import.meta.url)
const target = new URL('../src/builtin-fixtures.ts', import.meta.url)

const header = `// GENERATED by scripts/embed-fixtures.mjs from fixtures/*.json. Do not edit.
//
// The JSON directory is the source of truth; this is the copy the suite can
// import where there is no filesystem, such as a renderer's browser tests. The
// \`readonly Fixture[]\` annotation is load-bearing: it makes the package's
// typecheck a validator for every shipped case.
import type { Fixture } from './types.js'

export const builtinFixtures: readonly Fixture[] = `

const files = (await readdir(fixturesDirectory)).filter((file) => file.endsWith('.json')).sort()

const fixtures = []
for (const file of files) {
  const text = await readFile(new URL(file, fixturesDirectory), 'utf8')
  try {
    fixtures.push(JSON.parse(text))
  } catch (error) {
    throw new Error(`${file}: not valid JSON: ${error.message}`)
  }
}

await writeFile(fileURLToPath(target), `${header}${print(fixtures, 0)}\n`, 'utf8')
console.log(`Embedded ${fixtures.length} fixtures from ${files.length} files.`)

/** Prints JSON as TypeScript in the house style: single quotes, bare keys. */
function print(value, depth) {
  const pad = '  '.repeat(depth + 1)
  const closingPad = '  '.repeat(depth)

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    const items = value.map((item) => `${pad}${print(item, depth + 1)}`)
    return `[\n${items.join(',\n')},\n${closingPad}]`
  }

  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value)
    if (entries.length === 0) return '{}'
    const lines = entries.map(([key, item]) => `${pad}${printKey(key)}: ${print(item, depth + 1)}`)
    return `{\n${lines.join(',\n')},\n${closingPad}}`
  }

  return typeof value === 'string' ? quote(value) : JSON.stringify(value)
}

function printKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : quote(key)
}

function quote(text) {
  return `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}
