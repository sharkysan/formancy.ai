// Regenerates src/generated/document-validator.js from formancy.schema.json.
//
// The validator is compiled HERE, at authoring time, because compiling at
// runtime means ajv reaching for runtime code generation - which throws under
// the strict no-unsafe-eval CSP the product documents, in the browser-embedded
// builder, the one consumer that must call validateSchema.
//
// Run after any change to formancy.schema.json:
//   node scripts/generate-validator.mjs
// The csp.test.ts sync test fails if this is forgotten (schema-hash stamp).
import { readFileSync, writeFileSync } from 'node:fs'
import { Ajv2020 } from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
// The package's own canonical hash, from the built dist: the stamp below must
// be byte-identical to what schemaHash() computes in the sync test.
import { schemaHash } from '../dist/index.mjs'

const schemaUrl = new URL('../formancy.schema.json', import.meta.url)
const outUrl = new URL('../src/generated/document-validator.js', import.meta.url)

const schema = JSON.parse(readFileSync(schemaUrl, 'utf8'))

const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } })
const validate = ajv.compile(schema)

let code = standaloneCode(ajv, validate)

// ajv's esm mode fixes the EXPORT style but still emits require() for its
// runtime helpers (e.g. ucs2length). A require inside an ESM module makes
// bundlers inject a node:module createRequire shim - dead code in a browser,
// and exactly what this file exists to avoid. Hoist them into real imports,
// through an interop helper because the helpers are CJS with __esModule:
// under a bundler the default import is already the function, under plain
// node it is the exports object.
const imports = new Map()
code = code.replace(/require\("([^"]+)"\)\.default/g, (_match, specifier) => {
  let name = imports.get(specifier)
  if (!name) {
    name = `__runtime${imports.size}`
    imports.set(specifier, name)
  }
  return `_interopDefault(${name})`
})
if (/require\(/.test(code)) {
  throw new Error('generated validator still contains require() - hoisting missed a pattern')
}

const importLines = [...imports]
  // require() tolerates extensionless CJS paths; ESM import does not, and ajv
  // has no exports map to translate. Make the extension explicit.
  .map(([specifier, name]) => [specifier.endsWith('.js') ? specifier : `${specifier}.js`, name])
  .map(([specifier, name]) => `import ${name} from ${JSON.stringify(specifier)};`)
  .join('')
const interop =
  'const _interopDefault = (m) => (m && m.__esModule && m.default !== undefined ? m.default : m);'
code = code.replace('"use strict";', `"use strict";${importLines}${interop}`)

const header = `// GENERATED by scripts/generate-validator.mjs from formancy.schema.json.
// Do not edit; regenerate instead. Precompiled so validateSchema never invokes
// ajv's runtime compiler in the browser - see csp.test.ts for what that buys.
// schema-hash: ${schemaHash(schema)}
/* eslint-disable */
`

writeFileSync(outUrl, header + code)
console.log('wrote', outUrl.pathname)
