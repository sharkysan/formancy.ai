// `codecov.yml`, generated from the workspace.
//
// Two things in that file go stale by hand, and one of them is a failure this
// repository has already had. The component list is one row per package that
// produces coverage, and a package added without a row is simply absent from
// the report — the same shape as the three packages that sat on a weaker
// publication check than their twelve siblings until somebody counted. The other
// is the count of them, which nothing would contradict.
//
// So the list is derived. `node scripts/codecov-config.mjs --write` rewrites the
// file and `apps/docs/src/codecov.test.ts` fails when the committed file is not
// what this produces, naming that command.
//
// **The reasoning that belongs in `codecov.yml` is written here**, because a
// comment in a generated file survives exactly until the next run — which has
// happened in this repository once already, to a hand-written table in the spec
// reference. The YAML comments carry no markdown for the same reason they carry
// no backticks: nothing renders them, and the generator that emits them would
// have to escape every one.
//
// Built from a list of lines rather than one template literal, which is not
// style. A template literal holding YAML that quotes shell commands needs a
// backslash before every backtick, and getting one wrong is a syntax error in a
// generator whose output nothing would otherwise check.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Every workspace package with a `test:coverage` script, in path order.
 *
 * The script is the right thing to key on rather than the directory listing:
 * `packages/themes` has no suite because it is CSS, and a component for it would
 * report nothing forever and look like a package nobody tests.
 */
export function coveredPackages(repoRoot = root) {
  const found = []
  for (const group of ['packages', 'apps']) {
    for (const name of readdirSync(join(repoRoot, group)).sort()) {
      let manifest
      try {
        manifest = JSON.parse(readFileSync(join(repoRoot, group, name, 'package.json'), 'utf8'))
      } catch {
        continue
      }
      if (manifest.scripts?.['test:coverage'] === undefined) continue
      // An app and a package could share a name, and two components with one id
      // is a report that silently merges them.
      found.push({ path: `${group}/${name}`, id: group === 'apps' ? `app-${name}` : name })
    }
  }
  return found
}

