/** The file, as it should be on disk. */
export function codecovConfig(packages = coveredPackages()) {
  const components = packages.flatMap(({ path, id }) => [
    `    - component_id: ${id}`,
    `      name: ${path}`,
    '      paths:',
    `        - ${path}/**`,
  ])

  return `${[...HEADER, '', ...BODY, ...components, ...FOOTER].join('\n')}\n`
}

// `node scripts/codecov-config.mjs --write`
if (process.argv[1]?.endsWith('codecov-config.mjs')) {
  const text = codecovConfig()
  if (process.argv.includes('--write')) {
    writeFileSync(join(root, 'codecov.yml'), text, 'utf8')
    console.log(`codecov.yml: ${String(coveredPackages().length)} components`)
  } else {
    process.stdout.write(text)
  }
}
